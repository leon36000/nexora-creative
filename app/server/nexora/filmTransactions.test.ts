import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { expect, it, vi } from 'vitest';
import ts from 'typescript';
import { actionFacturation } from './credits.js';
import { soumissionIndeterminee } from './filmEchec.js';
import { creerVerificationArrets, statutTerminalConfirme } from './reconciliationArrets.js';

it('transfère et crée dans une seule transaction, puis confirme le prompt dans la même écriture', async () => {
  const dossier = mkdtempSync(join(tmpdir(), 'director-transaction-'));
  vi.doMock('../config.js', () => ({ config: { dataDir: dossier } }));
  const { takes } = await import('../jobs.js');
  const credit = { reservationId: 'r1', credits: 1, etat: 'reservee' };
  const ancien = takes.create({ project_id: null, kind: 'video', shot_name: 'ancien', settings: { nexoraCredits: credit } });
  const settings = { nexoraFilm: 1001, nexoraPlan: 0, nexoraClePlan: 'cle', nexoraSoumission: 'indeterminee', nexoraCredits: credit };
  expect(() => takes.createProtegee({ project_id: null, kind: null as unknown as string, shot_name: 'nouveau', settings }, 'cle', ancien)).toThrow();
  expect(JSON.parse(takes.get(ancien)!.settings).nexoraCredits.etat).toBe('reservee');
  const nouveau = takes.createProtegee({ project_id: null, kind: 'video', shot_name: 'nouveau', settings }, 'cle', ancien);
  expect(JSON.parse(takes.get(ancien)!.settings).nexoraCredits.etat).toBe('transferee');
  expect(JSON.parse(takes.get(nouveau)!.settings)).toMatchObject({ nexoraCredits: credit, nexoraSoumission: 'indeterminee' });
  takes.setPrompt(nouveau, 'job-synthetique');
  expect(takes.get(nouveau)).toMatchObject({ prompt_id: 'job-synthetique', status: 'rendering' });
  expect(JSON.parse(takes.get(nouveau)!.settings).nexoraSoumission).toBe('confirmee');
  takes.fail(nouveau, 'annulation demandée', true);
  expect(JSON.parse(takes.get(nouveau)!.settings).nexoraSoumission).toBe('indeterminee');
  const interrompue = takes.createProtegee({ project_id: null, kind: 'video', shot_name: 'interrompue', settings: { ...settings, nexoraFilm: 4, nexoraClePlan: 'autre-cle', nexoraCredits: { ...credit, reservationId: 'r2' } } }, 'autre-cle');
  takes.fail(interrompue, 'annulation demandée', true);
  takes.setPrompt(interrompue, 'job-potentiellement-actif');
  expect(takes.get(interrompue)).toMatchObject({ prompt_id: 'job-potentiellement-actif', status: 'stopped' });
  expect(JSON.parse(takes.get(interrompue)!.settings).nexoraSoumission).toBe('indeterminee');
  const perdu = takes.createProtegee({ project_id: null, kind: 'video', shot_name: 'sans-prompt', settings: { ...settings, nexoraFilm: 5, nexoraClePlan: 'cle-perdue', nexoraCredits: { ...credit, reservationId: 'r3' } } }, 'cle-perdue');
  takes.fail(perdu, 'annulation', true);
  const ancienHistorique = takes.create({ project_id: null, kind: 'video', shot_name: 'ancien-arrêt', settings: { autre: true } });
  takes.fail(ancienHistorique, 'ancien arrêt', true);
  const terminalConnu = takes.createProtegee({ project_id: null, kind: 'video', shot_name: 'terminal', settings: { nexoraFilm: 9, nexoraPlan: 0, nexoraClePlan: 'cle-terminal', nexoraSoumission: 'indeterminee' } }, 'cle-terminal');
  takes.setPrompt(terminalConnu, 'terminal-connu');
  takes.fail(terminalConnu, 'arrêt confirmé par le moteur', true, true);
  expect(JSON.parse(takes.get(terminalConnu)!.settings).nexoraSoumission).toBe('confirmee');
  takes.confirmerArretTerminal(nouveau, 'mauvais-prompt');
  expect(JSON.parse(takes.get(nouveau)!.settings).nexoraSoumission).toBe('indeterminee');
  let termine = false;
  const etat = vi.fn(async (id: string) => { if (id === 'job-potentiellement-actif') throw new Error('moteur inaccessible'); return termine; });
  const verifier = creerVerificationArrets((apres, limite) => takes.arretsIndetermines(apres, limite), etat, (id, prompt) => takes.confirmerArretTerminal(id, prompt), 50);
  await verifier();
  expect(JSON.parse(takes.get(nouveau)!.settings).nexoraSoumission).toBe('indeterminee');
  termine = true;
  await verifier();
  expect(takes.get(nouveau)!.status).toBe('stopped');
  expect(JSON.parse(takes.get(nouveau)!.settings).nexoraSoumission).toBe('confirmee');
  expect(JSON.parse(takes.get(interrompue)!.settings).nexoraSoumission).toBe('indeterminee');
  expect(JSON.parse(takes.get(perdu)!.settings).nexoraSoumission).toBe('indeterminee');
  expect(takes.get(ancienHistorique)!.status).toBe('stopped');
  expect(JSON.parse(takes.get(ancienHistorique)!.settings)).toEqual({ autre: true });
  expect(statutTerminalConfirme('expired')).toBe(false);
  expect(statutTerminalConfirme('succeeded')).toBe(true);

  const texte = readFileSync(new URL('../index.ts', import.meta.url), 'utf8');
  const source = ts.createSourceFile('index.ts', texte, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const fn = source.statements.find((n) => ts.isFunctionDeclaration(n) && n.name?.text === 'solderCreditsInterne');
  if (!fn) throw new Error('réconciliation introuvable');
  const js = ts.transpileModule(fn.getText(source), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None } }).outputText;
  const liberer = vi.fn(async () => {});
  const deps = { takes, soumissionIndeterminee, actionFacturation, facturationPour: () => ({ liberer }), accesOrganisation: () => ({}) };
  await new Function(...Object.keys(deps), `${js}; return solderCreditsInterne;`)(...Object.values(deps))();
  expect(liberer).toHaveBeenCalledOnce();
  expect(liberer).toHaveBeenCalledWith('r1');
  expect(JSON.parse(takes.get(nouveau)!.settings).nexoraCredits.etat).toBe('liberee');
  expect(JSON.parse(takes.get(interrompue)!.settings).nexoraCredits.etat).toBe('reservee');
});
