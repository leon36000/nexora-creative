export type CreationVideoCopy = typeof CREATION_VIDEO_COPY.fr;

export function creationVideoCopy(langue: LangueClient): CreationVideoCopy {
  return CREATION_VIDEO_COPY[langue] as CreationVideoCopy;
}

export function nomCameraCreation(langue: LangueClient, id: string, fallback: string): string {
  return (CREATION_VIDEO_COPY[langue].cameraNames as Record<string, string>)[id] ?? fallback;
}

export function erreurVisibleCreationVideo(error: unknown, fallback: string, network: string): string {
  if (!(error instanceof Error) || !error.message.trim()) return fallback;
  if (/^(failed to fetch|fetch failed|network error|networkerror|load failed)$/i.test(error.message.trim())) return network;
  return error.message;
}
